fn bp1_leaf_eligibility_is_one_shot_and_does_not_release_the_model_group() {
    let (mut model, w, e) = bound(ModelGoal::SyntheticLeaf);
    assert_eq!(model.evaluate(&w), PreloadDecisionV1::SyntheticLeafEligible);
    assert_eq!(model.evaluate(&w), PreloadDecisionV1::Denied(Error::Replay));
    let (p, s, mut next, _, _) = fixture();
    next.launch[0] ^= 1;
    next.nonce[0] ^= 1;
    let before = model.clone();
    assert_eq!(
        model.reserve(&p, &s, next, ModelGoal::SyntheticLeaf),
        Err(Error::Pending)
    );
    assert_eq!(model, before);
    model.end(&e).unwrap();
    assert_eq!(model.evaluate(&w), PreloadDecisionV1::Denied(Error::Replay));
    let (p, s, r, _, _) = fixture();
    assert_eq!(
        model.reserve(&p, &s, r, ModelGoal::SyntheticLeaf),
        Err(Error::Replay)
    );
}
