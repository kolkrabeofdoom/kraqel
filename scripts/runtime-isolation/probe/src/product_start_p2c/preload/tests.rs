fn bp1_readback_audit_optouts_and_identity_failures_consume_assessment() {
    for n in 0..8 {
        let (mut m, mut w, e) = bound(ModelGoal::SyntheticLeaf);
        match n {
            0 => w.readback_complete = false,
            1 => {
                w.enforced.remove(&Mitigation::NoRemoteImages);
                w.audited.insert(Mitigation::NoRemoteImages);
            }
            2 => w.actual_children = Children::RequiresBoundRole,
            3 => w.image_sha256[0] ^= 1,
            4 => w.support_sha256[0] ^= 1,
            5 => w.token_sha256[0] ^= 1,
            6 => w.handles_sha256[0] ^= 1,
            _ => {
                w.enforced.insert(Mitigation::DisableExtensionPoints);
            }
        };
        assert!(matches!(m.evaluate(&w), PreloadDecisionV1::Denied(_)));
        let (_, good, _) = bound(ModelGoal::SyntheticLeaf);
        assert_eq!(m.evaluate(&good), PreloadDecisionV1::Denied(Error::Replay));
        m.end(&e).unwrap();
    }
    for flag in 0..2 {
        let (mut p, mut s, mut r, mut w, _) = fixture();
        p.roles[0].required.insert(Mitigation::ProhibitDynamicCode);
        s.supported.insert(Mitigation::ProhibitDynamicCode);
        s.policy_sha256 = p.digest().unwrap();
        r.context.policy_sha256 = s.policy_sha256;
        w.request = r.clone();
        w.support_sha256 = s.digest().unwrap();
        w.enforced = p.root().required.clone();
        if flag == 0 {
            w.thread_opt_out = true;
        } else {
            w.remote_downgrade = true;
        }
        let mut m = PreloadModel::new(r.context.clone()).unwrap();
        m.reserve(&p, &s, r.clone(), ModelGoal::SyntheticLeaf)
            .unwrap();
        m.bind_root(&r, w.root).unwrap();
        assert_eq!(
            m.evaluate(&w),
            PreloadDecisionV1::Denied(Error::PolicyMismatch)
        );
    }
}
