fn bound(goal: ModelGoal) -> (PreloadModel, PreloadWitnessV1, ModelEndV1) {
    let (p, s, r, w, e) = fixture();
    let mut model = PreloadModel::new(r.context.clone()).unwrap();
    model.reserve(&p, &s, r.clone(), goal).unwrap();
    model.bind_root(&r, w.root).unwrap();
    (model, w, e)
}
fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

