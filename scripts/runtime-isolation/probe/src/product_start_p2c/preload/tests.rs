#[test]
fn bp1_decoders_reject_every_truncation_trailing_unknown_version_and_cross_domain() {
    let (p, s, _, w, e) = fixture();
    type Decoder = fn(&[u8]) -> bool;
    let cases: [(Vec<u8>, Decoder, usize); 4] = [
        (
            p.encode().unwrap(),
            |b| PreloadPolicyV1::decode(b).is_ok(),
            POLICY_DOMAIN.len(),
        ),
        (
            s.encode().unwrap(),
            |b| PreloadSupportV1::decode(b).is_ok(),
            MODEL_DOMAIN.len() + 1,
        ),
        (
            w.encode().unwrap(),
            |b| PreloadWitnessV1::decode(b).is_ok(),
            MODEL_DOMAIN.len() + 1,
        ),
        (
            e.encode().unwrap(),
            |b| ModelEndV1::decode(b).is_ok(),
            MODEL_DOMAIN.len() + 1,
        ),
    ];
    for (bytes, decode, version_offset) in &cases {
        for n in 0..bytes.len() {
            assert!(!decode(&bytes[..n]), "truncated {n}");
        }
        let mut bad = bytes.clone();
        bad.push(0);
        assert!(!decode(&bad));
        let mut bad = bytes.clone();
        bad[*version_offset] = 2;
        assert!(!decode(&bad));
        let mut bad = bytes.clone();
        bad[0] ^= 1;
        assert!(!decode(&bad));
        assert!(!decode(&vec![0; MAX_BYTES + 1]));
        for (other, _, _) in &cases {
            if other != bytes {
                assert!(!decode(other));
            }
        }
    }
}
#[test]
fn bp1_unknown_tags_booleans_and_noncanonical_sets_are_rejected() {
    let (p, s, _, _, _) = fixture();
    let bytes = p.encode().unwrap();
    let header = POLICY_DOMAIN.len() + 2 + 1 + 1 + 4 + 128 + 2 + 1;
    for (offset, value) in [
        (POLICY_DOMAIN.len() + 2, 2),
        (POLICY_DOMAIN.len() + 3, 2),
        (header, 0),
        (header, 7),
        (bytes.len() - 2, 3),
        (bytes.len() - 1, 2),
        (bytes.len() - 4, 8),
    ] {
        let mut bad = bytes.clone();
        bad[offset] = value;
        assert!(PreloadPolicyV1::decode(&bad).is_err());
    }
    let mut bad = bytes.clone();
    let n = bad.len();
    bad[n - 4] = 2;
    bad[n - 3] = 1;
    assert!(PreloadPolicyV1::decode(&bad).is_err());
    let mut bad = bytes.clone();
    bad[n - 3] = 1;
    assert!(PreloadPolicyV1::decode(&bad).is_err());
    let mut bad = s.encode().unwrap();
    bad[MODEL_DOMAIN.len()] = 0;
    assert!(PreloadSupportV1::decode(&bad).is_err());
    let mut bad = s.encode().unwrap();
    bad[MODEL_DOMAIN.len() + 1 + 2 + 1 + 4 + 32] = 2;
    assert!(PreloadSupportV1::decode(&bad).is_err());
}
#[test]
fn bp1_roles_sort_without_reinterpreting_webview_kinds() {
    let (mut p, _, _, _, _) = fixture();
    p.max_processes = 2;
    let mut child = p.roles[0].clone();
    child.role = Role::CrashHandler;
    p.roles.push(child);
    let sorted = p.encode().unwrap();
    p.roles.reverse();
    assert_eq!(p.encode().unwrap(), sorted);
    let header = POLICY_DOMAIN.len() + 2 + 1 + 1 + 4 + 128 + 2 + 1;
    let record = (sorted.len() - header) / 2;
    let mut bad = sorted[..header].to_vec();
    bad.extend(&sorted[header + record..]);
    bad.extend(&sorted[header..header + record]);
    assert!(PreloadPolicyV1::decode(&bad).is_err());
    let decoded = PreloadPolicyV1::decode(&sorted).unwrap();
    assert_eq!(decoded.roles[1].role, Role::CrashHandler);
    let mut duplicate = p.clone();
    duplicate.roles[1].role = Role::CrashHandler;
    assert!(duplicate.encode().is_err());
}
