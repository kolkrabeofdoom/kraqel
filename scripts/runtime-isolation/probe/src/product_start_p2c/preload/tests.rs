fn bp1_policy_limits_paths_digests_and_conflicts_fail_closed() {
    let (p, _, _, _, _) = fixture();
    for path in [
        "../ui.exe",
        "C:/ui.exe",
        "a\\b.exe",
        "NUL.txt",
        "a/../ui.exe",
        "e\u{301}.exe",
    ] {
        let mut bad = p.clone();
        bad.roles[0].image = path.into();
        assert!(bad.encode().is_err(), "{path}");
    }
    let mut bad = p.clone();
    bad.roles[0].image = "a".repeat(1025);
    assert!(bad.encode().is_err());
    let mut boundary = p.clone();
    boundary.roles[0].image = "a".repeat(1024);
    assert!(boundary.encode().is_ok());
    for max in [0, 17] {
        let mut bad = p.clone();
        bad.max_processes = max;
        assert!(bad.encode().is_err());
    }
    for instances in [0, 2, u16::MAX] {
        let mut bad = p.clone();
        bad.roles[0].max_instances = instances;
        assert!(bad.encode().is_err());
    }
    let mut bad = p.clone();
    bad.roles.clear();
    assert!(bad.encode().is_err());
    let mut bad = p.clone();
    bad.roles[0].role = Role::Browser;
    assert!(bad.encode().is_err());
    let mut bad = p.clone();
    bad.roles[0]
        .required
        .extend([Mitigation::MicrosoftSignedOnly, Mitigation::StoreSignedOnly]);
    assert!(bad.encode().is_err());
    for n in 0..8 {
        let mut bad = p.clone();
        match n {
            0 => bad.package_sha256 = [0; 32],
            1 => bad.controller_sha256 = [0; 32],
            2 => bad.platform_sha256 = [0; 32],
            3 => bad.environment_sha256 = [0; 32],
            4 => bad.roles[0].image_sha256 = [0; 32],
            5 => bad.roles[0].arguments_sha256 = [0; 32],
            6 => bad.roles[0].token_sha256 = [0; 32],
            _ => bad.roles[0].handles_sha256 = [0; 32],
        };
        assert!(bad.encode().is_err());
    }
}
#[test]
fn bp1_missing_support_is_not_masked_and_preflight_is_atomic() {
    let (p, s, r, _, _) = fixture();
    let model = PreloadModel::new(r.context.clone()).unwrap();
    for n in 0..5 {
        let mut bad = s.clone();
        match n {
            0 => bad.query_complete = false,
            1 => {
                bad.supported.remove(&Mitigation::NoRemoteImages);
            }
            2 => bad.os_build = p.min_os_build - 1,
            3 => bad.child_policy_supported = false,
            _ => {
                bad.supported.clear();
            }
        };
        let mut copy = model.clone();
        assert_eq!(
            copy.reserve(&p, &bad, r.clone(), ModelGoal::SyntheticLeaf),
            Err(Error::Unsupported)
        );
        assert_eq!(copy, model);
    }
    let mut missing = p.clone();
    missing.roles[0].required.clear();
    let mut new_r = r.clone();
    new_r.context.policy_sha256 = missing.digest().unwrap();
    let mut new_s = s;
    new_s.policy_sha256 = missing.digest().unwrap();
    let mut copy = PreloadModel::new(new_r.context.clone()).unwrap();
    let before = copy.clone();
    assert_eq!(
        copy.reserve(&missing, &new_s, new_r, ModelGoal::SyntheticLeaf),
        Err(Error::PolicyMismatch)
    );
    assert_eq!(copy, before);
}
#[test]
fn bp1_context_mutations_cannot_reserve_or_replace_a_bound_generation() {
    let (p, s, r, w, _) = fixture();
    for n in 0..6 {
        let mut bad = r.clone();
        match n {
            0 => bad.context.revision += 1,
            1 => bad.context.guardian.created += 1,
            2 => bad.context.guardian.pid += 1,
            3 => bad.context.job[0] ^= 1,
            4 => bad.context.policy_sha256[0] ^= 1,
            _ => bad.context.version += 1,
        };
        let mut m = PreloadModel::new(r.context.clone()).unwrap();
        let before = m.clone();
        assert!(m.reserve(&p, &s, bad, ModelGoal::SyntheticLeaf).is_err());
        assert_eq!(m, before);
    }
    let (mut m, _, _) = bound(ModelGoal::SyntheticLeaf);
    let before = m.clone();
    let mut bad = w.clone();
    bad.root.created += 1;
    assert_eq!(m.evaluate(&bad), PreloadDecisionV1::Denied(Error::Context));
    assert_eq!(m, before);
    bad = w.clone();
    bad.request.nonce[0] ^= 1;
    assert_eq!(m.evaluate(&bad), PreloadDecisionV1::Denied(Error::Context));
    assert_eq!(m, before);
}
